def _explain(key: str) -> str | None:
    if key in PRESET_TITLE:
        return _preset_text(key)
    return EXPLAIN.get(key)


@router.message(or_f(Command("guide"), F.text == BTN_GUIDE))
async def cmd_guide(message: Message) -> None:
    await message.answer(INDEX_TEXT, reply_markup=guide_keyboard())


@router.callback_query(F.data.startswith("why:"))
async def cb_why(cq: CallbackQuery) -> None:
    key = cq.data.split(":", 1)[1]
    if key == "index":
        text, markup = INDEX_TEXT, guide_keyboard()
    else:
        explanation = _explain(key)
        if explanation is None:          # unknown key: never leave a dead button
            await cq.answer("لا يوجد شرح لهذا الزر.", show_alert=True)
            return
        text, markup = explanation, guide_back_keyboard()

    # No parse_mode anywhere in the guide: these texts are full of ( ) * _ and
    # a parse error would blank the screen the admin came here to read.
    try:
        await cq.message.edit_text(text, reply_markup=markup)
    except Exception:
        # Same text tapped twice → "message is not modified", which is fine.
        pass
    await cq.answer()
